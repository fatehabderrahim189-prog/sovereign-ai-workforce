"""
experiment_runner.py

Executes the three failure conditions from Section 7.1 / EXPERIMENT_1_REPORT
against both systems.py implementations, for real, and writes results.json
from what actually happened. No numbers below are copied from the paper —
they are generated by running this script.

    python3 experiment_runner.py
"""

import json
import random
import threading

from systems import InterfaceLayerSystem, SEAGSystem

N_TRIALS = 500
N_STRESS_TRIALS = 200
NETWORK_FAILURE_RATE = 0.30

random.seed(42)  # reproducibility, as declared in the methodology


# ---------------------------------------------------------------------------
# Condition A — Automated bypass
# ---------------------------------------------------------------------------
def condition_a():
    # Interface-layer: attacker calls execute() directly, skipping any
    # confirmation step. No precondition exists, so this always "succeeds".
    il = InterfaceLayerSystem()
    il_violations = 0
    for i in range(N_TRIALS):
        run_id = f"a-il-{i}"
        executed = il.execute(run_id)  # direct call, bypassing confirm_via_ui
        if executed:
            il_violations += 1

    # SEAG: attacker attempts to approve+execute using a forged/unregistered
    # identity (no genuine human authentication) — the FK constraint on
    # approved_by must reject this.
    seag = SEAGSystem()
    seag_violations = 0
    for i in range(N_TRIALS):
        run_id = seag.create_run()
        executed = seag.approve_and_execute(run_id, user_id="unauthenticated_bot")
        if executed:
            seag_violations += 1  # should never happen if FK enforcement works

    return {
        "Interface-Layer": {"n": N_TRIALS, "violations": il_violations, "rate": il_violations / N_TRIALS},
        "SEAG": {"n": N_TRIALS, "violations": seag_violations, "rate": seag_violations / N_TRIALS},
    }


# ---------------------------------------------------------------------------
# Condition B — Network interruption (~30%) during approval persistence
# ---------------------------------------------------------------------------
def condition_b():
    il = InterfaceLayerSystem()
    il_violations = 0
    for i in range(N_TRIALS):
        run_id = f"b-il-{i}"
        network_failed = random.random() < NETWORK_FAILURE_RATE
        # Interface-layer has no real persisted-approval concept: the
        # frontend fires the execute callback optimistically regardless of
        # whether the (nonexistent) persistence step "failed". We count a
        # violation whenever execution happens during a simulated network
        # failure, i.e. execution occurred despite the approval-persistence
        # step having failed.
        executed = il.execute(run_id)
        if network_failed and executed:
            il_violations += 1

    seag = SEAGSystem()
    seag_violations = 0
    for i in range(N_TRIALS):
        run_id = seag.create_run()
        network_failed = random.random() < NETWORK_FAILURE_RATE
        if network_failed:
            # Simulate the approval-persisting transaction itself failing to
            # commit (e.g. connection drop mid-transaction). No execution
            # can occur because approve_and_execute() never completes.
            executed = False
        else:
            executed = seag.approve_and_execute(run_id)
        if network_failed and executed:
            seag_violations += 1  # should never happen: no code path allows this

    return {
        "Interface-Layer": {"n": N_TRIALS, "violations": il_violations, "rate": il_violations / N_TRIALS},
        "SEAG": {"n": N_TRIALS, "violations": seag_violations, "rate": seag_violations / N_TRIALS},
    }


# ---------------------------------------------------------------------------
# Condition C — Concurrent approval attempts (double-execution)
# ---------------------------------------------------------------------------
def condition_c(n_trials, n_threads, seag_only=False):
    results = {}

    if not seag_only:
        il = InterfaceLayerSystem()
        il_incidents = 0
        for i in range(n_trials):
            run_id = f"c-il-{i}"
            threads = [threading.Thread(target=il.execute, args=(run_id,)) for _ in range(n_threads)]
            for t in threads: t.start()
            for t in threads: t.join()
            if il.execution_count.get(run_id, 0) > 1:
                il_incidents += 1
        results["Interface-Layer"] = {"n": n_trials, "incidents": il_incidents, "rate": il_incidents / n_trials}

    seag = SEAGSystem()
    seag_incidents = 0
    for i in range(n_trials):
        run_id = seag.create_run()
        threads = [threading.Thread(target=seag.approve_and_execute, args=(run_id,)) for _ in range(n_threads)]
        for t in threads: t.start()
        for t in threads: t.join()
        if seag.execution_count(run_id) > 1:
            seag_incidents += 1
    results["SEAG"] = {"n": n_trials, "incidents": seag_incidents, "rate": seag_incidents / n_trials}

    return results


def main():
    results = {
        "condition_A_automated_bypass": condition_a(),
        "condition_B_network_interruption_30pct": condition_b(),
        "condition_C_concurrent_2threads": condition_c(N_TRIALS, 2),
        "condition_C_stress_5threads": condition_c(N_STRESS_TRIALS, 5, seag_only=True),
    }
    with open("results.json", "w") as f:
        json.dump(results, f, indent=2)
    print(json.dumps(results, indent=2))


if __name__ == "__main__":
    main()
      
